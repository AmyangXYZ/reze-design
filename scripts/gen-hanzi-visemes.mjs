// Generate lib/hanzi-visemes.ts from Unihan's kMandarin readings.
//
// Lip sync needs ONE fact per hanzi: which of the five MMD mouth shapes its
// syllable peaks in. That is the pinyin final's NUCLEUS — a if present, else
// o, else e, else the high vowel — so 20,992 characters compress to one
// string, one code each. Polyphones take kMandarin's primary reading; at
// five-viseme resolution a secondary reading almost never changes the shape.
//
// Run: node scripts/gen-hanzi-visemes.mjs path/to/Unihan_Readings.txt
import { readFileSync, writeFileSync } from "node:fs"

const src = readFileSync(process.argv[2], "utf8")
const BASE = 0x4e00
const SIZE = 0x9fff - BASE + 1
const table = new Array(SIZE).fill("0")
const CODE = { a: "1", i: "2", u: "3", e: "4", o: "5" }

function viseme(readingRaw) {
  // First reading, tone marks stripped (NFD drops combining marks), lowercased.
  const r = readingRaw
    .split(" ")[0]
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
  // Contracted finals whose written vowels hide the nucleus.
  if (r.endsWith("iu")) return "o" // iu = iou
  if (r.endsWith("ui")) return "e" // ui = uei
  if (r.includes("a")) return "a"
  if (r.includes("o")) return "o"
  if (r.includes("e")) return "e"
  if (r.includes("u")) return "u" // ü lost its diaeresis to NFD — same shape
  if (r.includes("i")) return "i"
  return null // m, n, ng interjections — the mouth stays closed
}

let n = 0
for (const line of src.split("\n")) {
  if (!line.includes("\tkMandarin\t")) continue
  const [cp, , reading] = line.split("\t")
  const code = parseInt(cp.slice(2), 16)
  if (code < BASE || code >= BASE + SIZE) continue
  const v = viseme(reading)
  table[code - BASE] = v ? CODE[v] : "0"
  n++
}

const out = `// GENERATED by scripts/gen-hanzi-visemes.mjs from Unihan kMandarin — do not edit.
// One code per character for U+4E00..U+9FFF: 0 none · 1 あ · 2 い · 3 う · 4 え · 5 お.
// The nucleus of each primary reading's final, which is where the mouth peaks.

const BASE = 0x4e00
const TABLE = "${table.join("")}"
const VISEME = [null, "a", "i", "u", "e", "o"] as const

/** The mouth shape a hanzi's Mandarin syllable peaks in, or null. */
export function hanziViseme(ch: string): "a" | "i" | "u" | "e" | "o" | null {
  const i = ch.charCodeAt(0) - BASE
  if (i < 0 || i >= ${SIZE}) return null
  return VISEME[TABLE.charCodeAt(i) - 48] ?? null
}
`
writeFileSync("lib/hanzi-visemes.ts", out)
console.log(`mapped ${n} readings; table ${SIZE} chars`)
